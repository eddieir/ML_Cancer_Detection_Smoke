"""
benchmarks/features.py — subject-aware feature construction for both tasks.

Two evaluation modes for Task A:
  * cell mode    — train directly on cells (see cap_cells_per_subject);
                   used by baselines.py's per-cell classifiers and the
                   neural adapter.
  * subject-summary mode — one feature vector per subject, built ONLY from
                   already train-fit gene representations (the
                   ExperimentContext's cell datasets already had
                   PreprocessingArtifact applied — fit on train cells only —
                   so aggregating here introduces no new leakage).

Task B always uses one feature vector per subject (a bag has no single
"label" to attach to individual cells).

No feature here is derived from an outcome (cancer_label) or from a
prediction generated by a model trained using that same subject outside its
own fold — see generate_out_of_fold_predictions for the one sanctioned way to
turn an upstream model's prediction into a downstream feature.
"""

from typing import Dict, List, Optional, Sequence, Tuple

import numpy as np


def cap_cells_per_subject(
    subject_ids: np.ndarray, max_cells_per_subject: int, seed: int = 42,
) -> np.ndarray:
    """
    Boolean keep-mask that caps how many of one subject's cells participate
    in a single cell-mode fit/epoch, so a subject with 10,000 cells cannot
    dominate a gradient step or a sklearn .fit() call the way a subject with
    100 cells never could. Sampling is deterministic given seed.
    """
    rng = np.random.RandomState(seed)
    keep = np.zeros(len(subject_ids), dtype=bool)
    for sid in sorted(set(subject_ids.tolist())):
        idx = np.where(subject_ids == sid)[0]
        if len(idx) <= max_cells_per_subject:
            keep[idx] = True
        else:
            chosen = rng.choice(idx, size=max_cells_per_subject, replace=False)
            keep[chosen] = True
    return keep


def _majority_label(labels: np.ndarray, num_classes: int) -> int:
    return int(np.bincount(labels.astype(int), minlength=num_classes).argmax())


def build_smoke_subject_summary_features(
    cell_dataset, num_cell_types: int, num_classes: int,
    feature_groups: Sequence[str] = ("gene_mean", "gene_std", "cell_type_prop", "n_cells"),
) -> Tuple[np.ndarray, np.ndarray, List[str], List[str]]:
    """
    One row per subject. Returns (X, y, subject_ids, feature_names).
    "n_cells" is kept as an explicitly separate, clearly-technical feature
    (not blended silently into the gene means) per the spec's requirement
    that cell count be identified as a technical covariate, not biology.
    """
    if len(cell_dataset) == 0:
        raise ValueError("build_smoke_subject_summary_features: empty cell_dataset")

    X_all = cell_dataset.X.numpy()
    smoke_all = cell_dataset.smoke.numpy()
    ctype_all = cell_dataset.ctype.numpy()
    subj_all = cell_dataset.subject_ids

    subject_ids = sorted(set(subj_all.tolist()))
    rows, y, feature_names = [], [], []

    n_genes = X_all.shape[1]
    for sid in subject_ids:
        mask = subj_all == sid
        Xs = X_all[mask]
        row = []
        if "gene_mean" in feature_groups:
            row.append(Xs.mean(axis=0))
        if "gene_std" in feature_groups:
            row.append(Xs.std(axis=0))
        if "cell_type_prop" in feature_groups:
            counts = np.bincount(ctype_all[mask], minlength=num_cell_types).astype(np.float64)
            row.append(counts / counts.sum())
        if "n_cells" in feature_groups:
            row.append(np.array([float(mask.sum())]))
        rows.append(np.concatenate(row))
        y.append(_majority_label(smoke_all[mask], num_classes))

    if "gene_mean" in feature_groups:
        feature_names += [f"gene_mean_{i}" for i in range(n_genes)]
    if "gene_std" in feature_groups:
        feature_names += [f"gene_std_{i}" for i in range(n_genes)]
    if "cell_type_prop" in feature_groups:
        feature_names += [f"cell_type_prop_{i}" for i in range(num_cell_types)]
    if "n_cells" in feature_groups:
        feature_names += ["n_cells"]

    return np.vstack(rows).astype(np.float32), np.array(y, dtype=np.int64), subject_ids, feature_names


def build_cancer_subject_features(
    bags: List[dict], num_cell_types: int,
    feature_groups: Sequence[str] = ("gene_mean", "cell_type_prop", "malignancy_known_mean", "n_cells"),
    oof_malignancy: Optional[Dict[str, float]] = None,
) -> Tuple[np.ndarray, np.ndarray, List[str], List[str]]:
    """
    One row per subject with a KNOWN cancer outcome (bags without one carry
    no label to train/evaluate against — see SubjectLevelDataset). No
    feature here is derived from cancer_label itself.

    oof_malignancy: optional {subject_id: out-of-fold predicted malignancy}
    — if given, adds a "malignancy_oof_pred" feature built from an upstream
    model's prediction generated WITHOUT using this subject in its training
    fold (see generate_out_of_fold_predictions). Passing an in-fold
    prediction here would be exactly the leakage this framework forbids.
    """
    known_bags = [b for b in bags if b.get("cancer_label_known")]
    if not known_bags:
        raise ValueError("build_cancer_subject_features: no bags with a known cancer outcome")

    rows, y, subject_ids = [], [], []
    n_genes = known_bags[0]["gene_matrix"].shape[1]
    for b in known_bags:
        row = []
        if "gene_mean" in feature_groups:
            row.append(b["gene_matrix"].mean(axis=0))
        if "cell_type_prop" in feature_groups:
            counts = np.bincount(b["cell_type_ids"], minlength=num_cell_types).astype(np.float64)
            row.append(counts / counts.sum())
        if "malignancy_known_mean" in feature_groups:
            known_mask = b["malig_known"]
            mean_malig = float(b["malig_labels"][known_mask].mean()) if known_mask.any() else 0.0
            has_known = float(known_mask.any())
            row.append(np.array([mean_malig, has_known]))
        if "n_cells" in feature_groups:
            row.append(np.array([float(len(b["gene_matrix"]))]))
        if oof_malignancy is not None:
            row.append(np.array([oof_malignancy.get(str(b["subject_id"]), 0.0)]))
        rows.append(np.concatenate(row))
        y.append(int(b["cancer_label"]))
        subject_ids.append(str(b["subject_id"]))

    feature_names = []
    if "gene_mean" in feature_groups:
        feature_names += [f"gene_mean_{i}" for i in range(n_genes)]
    if "cell_type_prop" in feature_groups:
        feature_names += [f"cell_type_prop_{i}" for i in range(num_cell_types)]
    if "malignancy_known_mean" in feature_groups:
        feature_names += ["malignancy_known_mean", "malignancy_has_known"]
    if "n_cells" in feature_groups:
        feature_names += ["n_cells"]
    if oof_malignancy is not None:
        feature_names += ["malignancy_oof_pred"]

    return np.vstack(rows).astype(np.float32), np.array(y, dtype=np.int64), subject_ids, feature_names


def generate_out_of_fold_predictions(
    fit_predict_fn, X: np.ndarray, y: np.ndarray, groups: Sequence[str],
    n_folds: int = 5, seed: int = 42,
) -> np.ndarray:
    """
    Generic out-of-fold predictor: for each grouped_kfold fold, fit
    fit_predict_fn on the fold's train rows and predict on its val rows,
    writing each subject's prediction only from a model that never saw that
    subject during fitting. Used to turn an upstream learned signal (e.g. a
    cell-level malignancy classifier) into a downstream Task B feature
    without leakage — see build_cancer_subject_features's oof_malignancy.

    fit_predict_fn(X_train, y_train, X_val) -> predictions for X_val.
    Raises if any row is left without a prediction (a grouped_kfold bug would
    otherwise silently zero-fill it).
    """
    from data.splitting import grouped_kfold

    groups = np.asarray([str(g) for g in groups])
    folds = grouped_kfold(groups, y, n_folds=n_folds, seed=seed)
    oof = np.full(len(y), np.nan, dtype=np.float64)

    for fold in folds:
        train_mask = np.isin(groups, fold["train"])
        val_mask = np.isin(groups, fold["val"])
        preds = fit_predict_fn(X[train_mask], y[train_mask], X[val_mask])
        oof[val_mask] = preds

    if np.isnan(oof).any():
        missing = int(np.isnan(oof).sum())
        raise RuntimeError(f"generate_out_of_fold_predictions: {missing} row(s) never got a fold assignment")
    return oof
